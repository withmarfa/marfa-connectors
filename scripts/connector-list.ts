/**
 * Writes `connectors.json`, the list of the connectors in `connectors/`, from
 * each connector's own definition: the `connector()` that its
 * `src/definition.ts` exports, built to `dist/definition.js`. Nothing in the
 * list is typed by hand, so a connector added to or removed from `connectors/`
 * changes it with no other edit.
 *
 * The list does not depend on who runs it: a definition is built from the
 * settings it is given, and this script gives it none, so no variable of the
 * caller's environment reaches it. A definition that declares a type only
 * under some setting also exports `settingsAddingTypes`, each such setting
 * with the values it takes, and the list names the types it declares under
 * each of them as well.
 *
 *   node --experimental-strip-types scripts/connector-list.ts          writes the file
 *   node --experimental-strip-types scripts/connector-list.ts --check  fails when it is out of date
 *
 * Run `pnpm build` first: the list is read from what the build made.
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { format, resolveConfig } from "prettier";
import {
  carriedTypes,
  type Connector,
  type EnvDeclaration,
  type EnvValues,
} from "@withmarfa/connector";

/** Where the list is written, from the repository root. */
export const listFile = "connectors.json";

/** Bumped when a reader of the file would have to change. */
export const schema = 1;

export interface ListedConnector {
  /** The connector's own folder, from the repository root. */
  directory: string;
  name: string;
  description?: string;
  source: string;
  sourceName?: string;
  /** An Iconify icon ID. */
  sourceMark?: string;
  /** The ID of each type the connector can write under any of its settings. */
  types: string[];
  /** Whether a change made in Marfa goes back to the vendor in the connector's default mode. */
  carriesBack: boolean;
  /** Whether a setting turns carrying back off, found by setting each optional setting to `true`. */
  carriesBackCanBeTurnedOff: boolean;
  /** The types whose changes can go back, a subset of `types`. */
  carriedTypes: string[];
}

export interface ConnectorList {
  schema: number;
  about: string;
  connectors: ListedConnector[];
}

const about =
  "Generated by `pnpm connectors:list` from each connector's definition; edit nothing here. " +
  "`types` lists every type the connector can write under any of its settings, not only the types it writes by default: a type that a setting adds, such as `rss.picture` for RSS when `RSS_PICTURES` is `save` or `save-in-library`, is included. " +
  "`carriesBack` is true when, in the connector's default mode, with every optional setting unset, it carries changes made in Marfa back to the vendor: it has an `onChange`, and `carries` (or, where it names none, every type) lists at least one type. " +
  "`carriesBackCanBeTurnedOff` is true when a setting or mode switches that off, found by setting each optional setting to `true` in turn and asking `carries` again: GitHub with a personal token or `GITHUB_READ_ONLY`, Todoist with `TODOIST_READ_ONLY` and Readwise Reader with `READWISE_READER_INBOUND_ONLY` are the connectors that have one. " +
  "So `carriesBack` says what a connector does by default, not what one owner's settings leave it doing. " +
  "A required setting is given a placeholder value when `carries` is asked.";

/** The environment the connector's `carries` is asked about. */
function defaultEnvironment(
  declaration: EnvDeclaration | undefined,
): Record<string, string | undefined> {
  return Object.fromEntries(
    Object.entries(declaration ?? {}).map(([name, kind]) => [
      name,
      kind === "optional" || kind === "optional-secret"
        ? undefined
        : "placeholder",
    ]),
  );
}

/** A connector's definition: how to build it, and the settings that add types. */
interface Definition {
  build: (settings: Settings) => Connector;
  settingsAddingTypes: Readonly<Record<string, readonly string[]>>;
}

type Settings = Readonly<Record<string, string | undefined>>;

async function definitionOf(
  root: string,
  directory: string,
): Promise<Definition> {
  const built = join(root, directory, "dist", "definition.js");
  let module: { connector?: unknown; settingsAddingTypes?: unknown };
  try {
    module = (await import(pathToFileURL(built).href)) as typeof module;
  } catch (error) {
    throw new Error(
      `${directory} has no built definition at ${directory}/dist/definition.js: run pnpm build, and keep its definition in src/definition.ts`,
      { cause: error },
    );
  }
  if (typeof module.connector !== "function") {
    throw new Error(
      `${directory}/src/definition.ts must export a function \`connector\` that returns the connector`,
    );
  }
  const adding: unknown = module.settingsAddingTypes ?? {};
  if (
    typeof adding !== "object" ||
    adding === null ||
    !Object.values(adding).every(
      (values) =>
        Array.isArray(values) &&
        values.every((value) => typeof value === "string"),
    )
  ) {
    throw new Error(
      `${directory}/src/definition.ts must export \`settingsAddingTypes\` as each setting's name with the array of values it takes`,
    );
  }
  return {
    build: module.connector as Definition["build"],
    settingsAddingTypes: adding as Definition["settingsAddingTypes"],
  };
}

function typesOf(connector: Connector): string[] {
  return connector.types.map((kind) => kind.type.id);
}

/** Every type the definition declares under the default settings or under any
 *  one value of a setting that adds types, the default's first. */
function allTypes(definition: Definition): string[] {
  const types = new Set(typesOf(definition.build({})));
  for (const [name, values] of Object.entries(definition.settingsAddingTypes)) {
    for (const value of values) {
      for (const type of typesOf(definition.build({ [name]: value }))) {
        types.add(type);
      }
    }
  }
  return [...types];
}

/** Whether setting one optional setting to `true` leaves no type carried. */
function canBeTurnedOff(connector: Connector): boolean {
  const base = defaultEnvironment(connector.env);
  return Object.entries(connector.env ?? {}).some(([name, kind]) => {
    if (kind !== "optional" && kind !== "optional-secret") return false;
    try {
      return (
        carriedTypes(connector, {
          ...base,
          [name]: "true",
        } as EnvValues<EnvDeclaration>).size === 0
      );
    } catch {
      return false;
    }
  });
}

function listed(directory: string, definition: Definition): ListedConnector {
  const connector = definition.build({});
  const types = allTypes(definition);
  const carried = carriedTypes(
    connector,
    defaultEnvironment(connector.env) as EnvValues<EnvDeclaration>,
  );
  const carriedList = types.filter((id) => carried.has(id));
  const carriesBack = carriedList.length > 0;
  return {
    directory,
    name: connector.name,
    ...(connector.description === undefined
      ? {}
      : { description: connector.description }),
    source: connector.source,
    ...(connector.sourceName === undefined
      ? {}
      : { sourceName: connector.sourceName }),
    ...(connector.sourceMark === undefined
      ? {}
      : { sourceMark: connector.sourceMark }),
    types,
    carriesBack,
    carriesBackCanBeTurnedOff: carriesBack && canBeTurnedOff(connector),
    carriedTypes: carriedList,
  };
}

/** The list for the repository at `root`, one entry per folder of `connectors/`. */
export async function connectorList(root: string): Promise<ConnectorList> {
  const folders = (
    await readdir(join(root, "connectors"), { withFileTypes: true })
  )
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
  const connectors: ListedConnector[] = [];
  for (const folder of folders) {
    const directory = `connectors/${folder}`;
    connectors.push(listed(directory, await definitionOf(root, directory)));
  }
  return { schema, about, connectors };
}

/** The file's text, formatted as `pnpm format` leaves it. */
export async function render(root: string): Promise<string> {
  const path = join(root, listFile);
  const options = (await resolveConfig(path)) ?? {};
  return format(JSON.stringify(await connectorList(root)), {
    ...options,
    filepath: path,
  });
}

async function main(): Promise<void> {
  const root = resolve(import.meta.dirname, "..");
  const text = await render(root);
  const path = join(root, listFile);
  if (process.argv.includes("--check")) {
    const current = await readFile(path, "utf8").catch(() => undefined);
    if (current !== text) {
      console.error(
        `${listFile} is out of date with the connectors' definitions: run pnpm build, then pnpm connectors:list, and commit the result`,
      );
      process.exitCode = 1;
    }
    return;
  }
  await writeFile(path, text);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  await main();
}
