/**
 * Writes `connectors.json`, the list of the connectors in `connectors/`, from
 * each connector's own definition: the `connector()` that its
 * `src/definition.ts` exports, built to `dist/definition.js`. Nothing in the
 * list is typed by hand, so a connector added to or removed from `connectors/`
 * changes it with no other edit.
 *
 *   node --experimental-strip-types scripts/connector-list.ts          writes the file
 *   node --experimental-strip-types scripts/connector-list.ts --check  fails when it is out of date
 *
 * Run `pnpm build` first: the list is read from what the build made.
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { format, resolveConfig } from "prettier";
import {
  carriedTypes,
  type Connector,
  type EnvDeclaration,
  type EnvValues,
} from "@withmarfa/connector";

/** Where the list is written, from the repository root. */
export const listFile = "connectors.json";

/** Bumped when a reader of the file would have to change. */
export const schema = 1;

export interface ListedConnector {
  /** The connector's own folder, from the repository root. */
  directory: string;
  name: string;
  description?: string;
  source: string;
  sourceName?: string;
  /** An Iconify icon ID. */
  sourceMark?: string;
  /** The ID of each type the connector writes. */
  types: string[];
  /** Whether a change made in Marfa can go back to the vendor. */
  carriesBack: boolean;
  /** The types whose changes can go back, a subset of `types`. */
  carriedTypes: string[];
}

export interface ConnectorList {
  schema: number;
  about: string;
  connectors: ListedConnector[];
}

const about =
  "Generated by `pnpm connectors:list` from each connector's definition; edit nothing here. " +
  "`carriesBack` is true when, with every optional setting unset, the connector carries changes made in Marfa back to the vendor: " +
  "it has an `onChange`, and `carries` (or, where it names none, every type) lists at least one type. " +
  "A setting that turns writing back off, such as a read-only mode, is not applied, so the list says what the connector does by default, not what one owner's settings leave it doing. " +
  "A required setting is given a placeholder value when `carries` is asked.";

/** The environment the connector's `carries` is asked about. */
function defaultEnvironment(
  declaration: EnvDeclaration | undefined,
): Record<string, string | undefined> {
  return Object.fromEntries(
    Object.entries(declaration ?? {}).map(([name, kind]) => [
      name,
      kind === "optional" || kind === "optional-secret"
        ? undefined
        : "placeholder",
    ]),
  );
}

async function definitionOf(
  root: string,
  directory: string,
): Promise<Connector> {
  const built = join(root, directory, "dist", "definition.js");
  let module: { connector?: unknown };
  try {
    module = (await import(pathToFileURL(built).href)) as typeof module;
  } catch (error) {
    throw new Error(
      `${directory} has no built definition at ${directory}/dist/definition.js: run pnpm build, and keep its definition in src/definition.ts`,
      { cause: error },
    );
  }
  if (typeof module.connector !== "function") {
    throw new Error(
      `${directory}/src/definition.ts must export a function \`connector\` that returns the connector`,
    );
  }
  return (module.connector as () => Connector)();
}

function listed(directory: string, connector: Connector): ListedConnector {
  const types = connector.types.map((kind) => kind.type.id);
  const carried = carriedTypes(
    connector,
    defaultEnvironment(connector.env) as EnvValues<EnvDeclaration>,
  );
  const carriedList = types.filter((id) => carried.has(id));
  return {
    directory,
    name: connector.name,
    ...(connector.description === undefined
      ? {}
      : { description: connector.description }),
    source: connector.source,
    ...(connector.sourceName === undefined
      ? {}
      : { sourceName: connector.sourceName }),
    ...(connector.sourceMark === undefined
      ? {}
      : { sourceMark: connector.sourceMark }),
    types,
    carriesBack: carriedList.length > 0,
    carriedTypes: carriedList,
  };
}

/** The list for the repository at `root`, one entry per folder of `connectors/`. */
export async function connectorList(root: string): Promise<ConnectorList> {
  const folders = (
    await readdir(join(root, "connectors"), { withFileTypes: true })
  )
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
  const connectors: ListedConnector[] = [];
  for (const folder of folders) {
    const directory = `connectors/${folder}`;
    connectors.push(listed(directory, await definitionOf(root, directory)));
  }
  return { schema, about, connectors };
}

/** The file's text, formatted as `pnpm format` leaves it. */
export async function render(root: string): Promise<string> {
  const path = join(root, listFile);
  const options = (await resolveConfig(path)) ?? {};
  return format(JSON.stringify(await connectorList(root)), {
    ...options,
    filepath: path,
  });
}

async function main(): Promise<void> {
  const root = resolve(import.meta.dirname, "..");
  const text = await render(root);
  const path = join(root, listFile);
  if (process.argv.includes("--check")) {
    const current = await readFile(path, "utf8").catch(() => undefined);
    if (current !== text) {
      console.error(
        `${listFile} is out of date with the connectors' definitions: run pnpm build, then pnpm connectors:list, and commit the result`,
      );
      process.exitCode = 1;
    }
    return;
  }
  await writeFile(path, text);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  await main();
}
