#!/usr/bin/env bash
# What .github/workflows/follow-releases.yml decides and writes, kept here so a
# test can pin it.
#
#   scripts/follow-release.sh decide pin=<commit> kit=<version> scripts=<version> \
#     tag=<tag> release=<commit> relation=<state> published=<yes|no> open=<count>
#   scripts/follow-release.sh apply <commit> <version>
#
# decide prints `bump`, or `skip: <reason>` where the connectors stay as they
# are. The arguments:
#   pin        the commit in scripts/monorepo.commit
#   kit        the @withmarfa/client version in kit/package.json
#   scripts    the @withmarfa/client version in scripts/package.json
#   tag        the newest published (not draft, not pre-release) marfa release, v<version>
#   release    the commit that tag names
#   relation   the release commit compared with the pin, as GitHub's compare
#              answers it: identical, ahead (the release has commits the pin
#              lacks), behind (the pin has commits the release lacks) or diverged
#   published  whether npm serves @withmarfa/client at the release's version
#   open       how many open pull requests change scripts/monorepo.commit
#
# apply writes the commit into scripts/monorepo.commit and the version into
# both manifests, as exact versions. The lockfile is regenerated by the caller.
set -euo pipefail

die() {
  echo "follow-release.sh: $*" >&2
  exit 1
}

sha='^[0-9a-f]{40}$'
semver='^[0-9]+\.[0-9]+\.[0-9]+$'

# True when $1 is a lower version than $2.
older() {
  [[ "$1" != "$2" && "$(printf '%s\n%s\n' "$1" "$2" | sort -V | head -n 1)" == "$1" ]]
}

decide() {
  local pin="" kit="" scripts="" tag="" release="" relation="" published="" open="" arg
  for arg in "$@"; do
    case "${arg}" in
      pin=*) pin="${arg#pin=}" ;;
      kit=*) kit="${arg#kit=}" ;;
      scripts=*) scripts="${arg#scripts=}" ;;
      tag=*) tag="${arg#tag=}" ;;
      release=*) release="${arg#release=}" ;;
      relation=*) relation="${arg#relation=}" ;;
      published=*) published="${arg#published=}" ;;
      open=*) open="${arg#open=}" ;;
      *) die "'${arg}' is not an argument" ;;
    esac
  done
  [[ "${pin}" =~ ${sha} ]] || die "'${pin}' is not a commit"
  [[ "${release}" =~ ${sha} ]] || die "'${release}' is not a commit"
  [[ "${tag}" =~ ^v[0-9]+\.[0-9]+\.[0-9]+$ ]] || die "'${tag}' is not a release tag"
  local version="${tag#v}"
  [[ "${kit}" =~ ${semver} ]] || die "'${kit}' is not an exact version"
  [[ "${scripts}" =~ ${semver} ]] || die "'${scripts}' is not an exact version"
  case "${relation}" in identical | ahead | behind | diverged) ;; *) die "'${relation}' is not a relation" ;; esac
  case "${published}" in yes | no) ;; *) die "'${published}' is not yes or no" ;; esac
  [[ "${open}" =~ ^[0-9]+$ ]] || die "'${open}' is not a count"
  # The relation is of two commits, so it has to agree with them.
  if [[ "${pin}" == "${release}" && "${relation}" != identical ]] ||
    [[ "${pin}" != "${release}" && "${relation}" == identical ]]; then
    die "relation '${relation}' does not fit the pin and the release commit"
  fi

  if [[ "${relation}" == behind || "${relation}" == diverged ]]; then
    echo "skip: the pin is not an ancestor of ${tag}, so it is ahead of the release or off its line"
  elif older "${version}" "${kit}" || older "${version}" "${scripts}"; then
    echo "skip: a client is newer than ${tag}"
  elif [[ "${relation}" == identical && "${kit}" == "${version}" && "${scripts}" == "${version}" ]]; then
    echo "skip: the connectors follow ${tag} already"
  elif ((open > 0)); then
    echo "skip: a pull request that moves the pin is open"
  elif [[ "${published}" == no ]]; then
    echo "skip: @withmarfa/client ${version} is not published yet"
  else
    echo bump
  fi
}

apply() {
  local commit="${1:?}" version="${2:?}"
  [[ "${commit}" =~ ${sha} ]] || die "'${commit}' is not a commit"
  [[ "${version}" =~ ${semver} ]] || die "'${version}' is not an exact version"
  local root manifest
  root="$(cd "$(dirname "$0")/.." && pwd)"
  # Everything is checked before anything is written, so a failure changes nothing.
  for manifest in kit/package.json scripts/package.json; do
    [[ "$(grep -c '"@withmarfa/client": "' "${root}/${manifest}")" == 1 ]] ||
      die "${manifest} does not name @withmarfa/client exactly once"
  done
  echo "${commit}" >"${root}/scripts/monorepo.commit"
  for manifest in kit/package.json scripts/package.json; do
    # The one line that names the client is rewritten in place, so the rest of
    # the file keeps every byte.
    sed -E -i.bak "s|(\"@withmarfa/client\": \")[^\"]+(\")|\1${version}\2|" "${root}/${manifest}"
    rm "${root}/${manifest}.bak"
  done
}

case "${1:-}" in
  decide)
    shift
    decide "$@"
    ;;
  apply) apply "${2:-}" "${3:-}" ;;
  *)
    echo "usage: scripts/follow-release.sh decide pin=.. kit=.. scripts=.. tag=.. release=.. relation=.. published=.. open=.." >&2
    echo "       scripts/follow-release.sh apply <commit> <version>" >&2
    exit 2
    ;;
esac
